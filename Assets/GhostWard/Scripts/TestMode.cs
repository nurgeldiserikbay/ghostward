namespace GhostWard
{
    // Тестовая сборка — один флаг на всё, что нужно при проверке и не должно попасть к игрокам.
    // Перед выкладкой в Google Play — false (сборка напомнит об этом в логе).
    //
    // Что включает:
    //  • диагностика в правом верхнем углу: режим камеры (AR / гироскоп), карта темноты, глубина,
    //    высота телефона, потолок, выбранное место, микрофон, сущность этой ночи и где её логово;
    //  • в дневнике у каждой сущности — блок «ТЕСТ»: все улики, приманка, чем изгонять и как, где прячется,
    //    как охотится (даже у ещё не встреченных);
    //  • кнопка «Тест: следующей ночью» в статье дневника — выбрать, кто придёт;
    //  • все виды камеры открыты без покупки;
    //  • «одержимость» (маска на людях) — каждую ночь, кроме пролога.
    public static class TestMode
    {
        // Сборка для Google Play (GhostWard → Собрать AAB) ставит символ GHOSTWARD_RELEASE — тогда выключено само.
#if GHOSTWARD_RELEASE
        public static readonly bool On = false;
#else
        public static readonly bool On = true;
#endif
    }
}
