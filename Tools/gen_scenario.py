def parse(path):
    table = {}
    text = open(path, encoding='utf-8').read()
    for m in re.finditer(r'\["([^"]+)"\]\s*=\s*new\[\]\s*\{', text):
        key, i, vals = m.group(1), m.end(), []
        while True:
            while text[i] in ' \n\r\t,':
                i += 1
            if text[i] == '}':
                break
            assert text[i] == '"', (key, text[i:i + 20])
            i += 1
            buf = []
            while text[i] != '"':
                if text[i] == '\\':
                    nxt = text[i + 1]
                    buf.append('\n' if nxt == 'n' else nxt)
                    i += 2
                else:
                    buf.append(text[i])
                    i += 1
            vals.append(''.join(buf))
            i += 1
        table[key] = vals
    return table


