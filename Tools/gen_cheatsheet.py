# Собирает docs/CHEATSHEET.md — шпаргалку для тестирования: как найти и чем прогнать каждую сущность.
# Данные берутся из кода игры (Catalog.cs, Knowledge.cs, Strings.cs) и описаний механики из gen_scenario.py.
# Запуск из корня проекта: python Tools/gen_cheatsheet.py
import ast
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPTS = os.path.join(ROOT, 'Assets', 'GhostWard', 'Scripts')
OUT = os.path.join(ROOT, 'docs', 'CHEATSHEET.md')
LANG = 1  # ru


def read(name):
    return open(os.path.join(SCRIPTS, name), encoding='utf-8').read()


def unescape(v):
    return v.replace('\\"', '"').replace('\\n', ' ').replace('\\\\', '\\')


T = {}
for m in re.finditer(r'\["([^"]+)"\] = new\[\] \{(.*?)\},\n', read('Strings.cs'), re.S):
    T[m.group(1)] = [unescape(x) for x in re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2))]


def t(key):
    row = T.get(key)
    return row[LANG] if row else f'«{key}»'


catalog = read('Catalog.cs')
kinds = [k.strip() for k in re.search(r'enum EntityKind\s*\{([^}]*)\}', catalog).group(1).replace('\n', ' ').split(',') if k.strip()]
defs = {}
for m in re.finditer(r'Kind = EntityKind\.(\w+), Lure = Lure\.(\w+), Bane = ItemKind\.(\w+).*?Stance = Stance\.(\w+).*?'
                     r'Clues = new\[\] \{([^}]*)\}, Lair = Lair\.(\w+)', catalog, re.S):
    defs[m.group(1)] = dict(lure=m.group(2), bane=m.group(3), stance=m.group(4),
                            clues=re.findall(r'Evidence\.(\w+)', m.group(5)), lair=m.group(6))
unlock = [int(x) for x in re.findall(r'\d+', re.search(r'UnlockXp =\s*\{([^}]*)\}', read('Knowledge.cs')).group(1))]
invisible = re.search(r'Invisible => (.*?);', catalog).group(1)
invisible = re.findall(r'EntityKind\.(\w+)', invisible)

gen = open(os.path.join(ROOT, 'Tools', 'gen_scenario.py'), encoding='utf-8').read()
behavior = ast.literal_eval(re.search(r'BEHAVIOR = (\{.*?\n\})', gen, re.S).group(1))

GESTURE = {'Salt': 'смахнуть вверх', 'Lantern': 'зажать палец и держать в луче', 'Iron': 'двойное касание, вплотную',
           'Bell': 'встряхнуть телефон, повернувшись к ней', 'Mirror': 'смахнуть вниз, глядя на неё',
           'Wormwood': 'зигзаг пальцем влево-вправо, глядя на неё'}
LAIR = {'DarkCorner': 'самый тёмный угол', 'Floor': 'низко, у пола', 'Behind': 'за спиной (куда не смотрел в начале)',
        'Ceiling': 'под потолком', 'Bright': 'самое светлое / отражающее место', 'Near': 'рядом, 1,4–2,2 м',
        'Far': 'дальний тёмный проём, 4–5 м'}
FIND = {
    'Frost': 'тепловизор на логово: ниже нуля и синее пятно',
    'Whisper': 'шёпот из одной точки (в наушниках слышно сторону)',
    'Compass': 'ЭМП показывает 5, когда наведён на логово',
    'Static': 'картинка рвётся помехами, когда камера смотрит на логово',
    'Knock': 'три стука из одного места (скрип пола — не улика)',
    'Radio': 'радио духов: спросить вслух — ответит искажённым голосом',
    'NightVision': 'ночная камера: в логове на миг мелькает силуэт',
    'Prints': 'тепловизор, смотреть на пол: холодные следы ведут к логову',
}

L = []
w = L.append
w('# GhostWard — шпаргалка для тестирования')
w('')
w('> Собирается из кода игры скриптом `Tools/gen_cheatsheet.py` — всегда совпадает с тем, что в игре.')
w('')
w('## Как идёт ночь')
w('')
w('1. **Осмотр комнаты** — медленно поверни телефон, игра строит карту темноты и выбирает логово по привычке сущности.')
w('2. **Расследование** — сущность сидит в логове и не видна. Её выдают улики (3 из 8). Отмечай их в Дневнике → Улики: '
  'снизу появится список подходящих. Компас после каждой улики на несколько секунд показывает метку в сторону логова.')
w('3. **Назови её** — в статье дневника кнопка «Это она». Верно — на охоте она слабее и сразу появится подсказка, чем её прогнать. '
  'Неверно — охота начнётся сразу и в ярости.')
w('4. **Охота** — когда злость полная (или сразу после неверного имени) она выходит. Тишина и неподвижность прячут, шум выдаёт. '
  'Прогони её нужным предметом. Иначе — дожить до рассвета (5 минут).')
w('5. **Страх** — первый раз за ночь при 100% будет обморок (очнёшься с 60%), второй раз — конец ночи.')
w('')
w('**Тест конкретной сущности:** Дневник → её статья → «Тест: следующей ночью» (кнопка есть, пока включён тестовый режим).')
w('')
w('## Как найти каждую улику')
w('')
w('| Улика | Чем и как |')
w('|---|---|')
for c in ['Frost', 'Whisper', 'Compass', 'Static', 'Knock', 'Radio', 'NightVision', 'Prints']:
    w(f"| {t(f'c.{c}.name')} | {FIND[c]} |")
w('')
w('## Предметы')
w('')
w('| Предмет | Жест | Важно |')
w('|---|---|---|')
w(f"| {t('i.Salt.name')} | {GESTURE['Salt']} | смотреть на неё, до 4,5 м |")
w(f"| {t('i.Lantern.name')} | {GESTURE['Lantern']} | горит ~1,6 с в луче (упырь дольше); тратит заряд |")
w(f"| {t('i.Iron.name')} | {GESTURE['Iron']} | только близко: 2,6 м без AR, 1,8 м в AR |")
w(f"| {t('i.Bell.name')} | {GESTURE['Bell']} | невидимок — повернувшись на шум (±45°); мару — в любой стороне |")
w(f"| {t('i.Mirror.name')} | {GESTURE['Mirror']} | смотреть на неё, до 5 м |")
w(f"| {t('i.Wormwood.name')} | {GESTURE['Wormwood']} | смотреть на неё, до 4 м |")
w('')
w('Неверный предмет злит сущность (быстрее) и добавляет страх.')
w('')
w('## Все сущности')
w('')
w('| # | Сущность | Опыт | Улики | Где логово | Приманка | Чем прогнать | Как ведёт себя на охоте |')
w('|---|---|---|---|---|---|---|---|')
for i, k in enumerate(kinds):
    d = defs[k]
    clues = ', '.join(t(f'c.{c}.name') for c in d['clues'])
    name = t(f'e.{k}.name') + (' — не видно' if k in invisible else '')
    bane = f"**{t('i.' + d['bane'] + '.name')}** — {GESTURE[d['bane']]}"
    w(f"| {i + 1} | {name} | {unlock[i]} | {clues} | {LAIR[d['lair']]} | {t('l.' + d['lure'] + '.name')} | {bane} | {behavior.get(k, '')} |")
w('')
w('## Частые затыки')
w('')
w('- **Невидимые (Полтергейст, Домовой, Ведьма Белла)** — их не видно никогда. На охоте они швыряют вещи. '
  'Повернись туда, откуда грохот, и встряхни телефон (колокольчик). Повернуться надо в пределах ±45° от звука.')
w('- **Албасты, Жезтырнак, Подменыш, Кицунэ, Асванг, Шурале** — двигаются, только когда на них не смотришь. '
  'Чтобы подошли — отвернись, потом резко повернись. Для железа нужно подпустить на 2,6 м.')
w('- **Мара, Кутисакэ-онна** — появляются рядом и стоят ~14 с, потом бьют. Долго не смотри — страх растёт втрое быстрее.')
w('- **Русалка, Кровавая Мэри, Водяной** — под долгим взглядом (1,4 с) уходят и всплывают ближе. Действуй быстрым взглядом.')
w('- **Джинн, Убыр, Пенанггалан** — кружат вокруг, сужая круг. Лови взглядом на круге.')
w('- **Чёрный пёс** — глазом почти не виден: включи ночную камеру или тепловизор.')
w('- **Кикимора, Ла Лечуса** — ползут по потолку: смотри вверх, вблизи падают вниз.')
w('')
open(OUT, 'w', encoding='utf-8').write('\n'.join(L))
print('written', OUT, len(L), 'lines')
